import { describe, it, expect } from "vitest";
import { parseDigest, digestUserPrompt, shouldAutoGenerateDigest } from "@/lib/digest";

describe("parseDigest", () => {
  it("parses a complete digest", () => {
    const d = parseDigest(
      JSON.stringify({
        highlights: ["You both named the same favorite memory"],
        appreciations: ["P1 noticed P2's effort with the kids"],
        gentle_suggestion: "Try a six-minute check-in at handoff.",
        reflection: "A steady week.",
      }),
    );
    expect(d.highlights).toHaveLength(1);
    expect(d.gentle_suggestion).toMatch(/six-minute/);
  });

  it("extracts JSON wrapped in prose and coerces bad fields", () => {
    const d = parseDigest(
      'Sure! {"highlights":["a", 3],"appreciations":"nope","gentle_suggestion":null,"reflection":"ok"}',
    );
    expect(d.highlights).toEqual(["a"]);
    expect(d.appreciations).toEqual([]);
    expect(d.gentle_suggestion).toBe("");
    expect(d.reflection).toBe("ok");
  });

  it("degrades to empty defaults on garbage", () => {
    const d = parseDigest("model fell over");
    expect(d).toEqual({
      highlights: [],
      appreciations: [],
      gentle_suggestion: "",
      reflection: "",
    });
  });
});

describe("digestUserPrompt", () => {
  it("includes titles, questions, and both redacted answers", () => {
    const msg = digestUserPrompt("romantic", [
      { title: "Daily question", question: "High of the day?", p1: "the park", p2: "" },
    ]);
    expect(msg.content).toContain("[Daily question] High of the day?");
    expect(msg.content).toContain("P1: the park");
    expect(msg.content).toContain("P2: (no answer)");
  });
});

describe("digestUserPrompt goals", () => {
  it("adds the shared list only when present and caps it at ten", () => {
    const items = [{ title: "Daily", question: "Q?", p1: "a", p2: "b" }];
    expect(digestUserPrompt("friend", items).content).not.toContain("trying together");
    const goals = Array.from({ length: 12 }, (_, i) => `goal ${i}`);
    const c = digestUserPrompt("friend", items, goals).content;
    expect(c).toContain("trying together");
    expect(c).toContain("- goal 9");
    expect(c).not.toContain("- goal 10");
  });
});

describe("shouldAutoGenerateDigest", () => {
  const now = Date.parse("2026-10-18T12:00:00Z");
  const base = {
    isPremium: true,
    aiEnabled: true,
    hasMaterial: true,
    pending: false,
    lastGeneratedAt: null as string | null,
    nowMs: now,
  };
  const daysAgo = (d: number) => new Date(now - d * 24 * 60 * 60 * 1000).toISOString();

  it("writes the first digest as soon as a week has revealed answers", () => {
    expect(shouldAutoGenerateDigest(base)).toBe(true);
  });

  it("waits a full week after the last digest", () => {
    expect(shouldAutoGenerateDigest({ ...base, lastGeneratedAt: daysAgo(6.9) })).toBe(false);
    expect(shouldAutoGenerateDigest({ ...base, lastGeneratedAt: daysAgo(7) })).toBe(true);
  });

  it("never runs without Premium, AI, material, or while one is being written", () => {
    expect(shouldAutoGenerateDigest({ ...base, isPremium: false })).toBe(false);
    expect(shouldAutoGenerateDigest({ ...base, aiEnabled: false })).toBe(false);
    expect(shouldAutoGenerateDigest({ ...base, hasMaterial: false })).toBe(false);
    expect(shouldAutoGenerateDigest({ ...base, pending: true })).toBe(false);
  });

  it("treats an unreadable date as not due", () => {
    expect(shouldAutoGenerateDigest({ ...base, lastGeneratedAt: "nope" })).toBe(false);
  });
});
