import Link from "next/link";
import { after } from "next/server";
import { createClient } from "@/lib/supabase/server";
import { generateWeeklyDigest } from "@/app/actions/digest";
import { DIGEST_MIN_GAP_MS, runWeeklyDigest } from "@/lib/weeklyDigest";
import { shouldAutoGenerateDigest } from "@/lib/digest";
import { aiEnabled } from "@/lib/grok";
import { INLINE_RESOURCES, SAFETY_NOTE, SAFETY_PRIVACY_LINE } from "@/lib/safety";
import { isPendingInsightPayload } from "@/lib/insightRateLimit";
import PendingButton from "@/components/PendingButton";

type Payload = {
  safety?: boolean;
  highlights?: string[];
  appreciations?: string[];
  gentle_suggestion?: string;
  reflection?: string;
};

// Weekly digest card for the connection page (server component). Premium
// generates; everyone sees the latest digest once it exists (it's a shared
// insight). Safety-withheld digests render support resources instead.
//
// Generate on visit (decision 0001, option A): when the week's digest is due,
// opening the hub writes it after the page is sent, in this member's own
// session, so the RLS reveal gate still bounds what the AI sees. It shows up
// on the next visit; the button stays for anyone who wants it sooner.
export default async function WeeklyDigest({
  connectionId,
}: {
  connectionId: string;
}) {
  const supabase = await createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();
  if (!user) return null;

  const { data: insight } = await supabase
    .from("relationship_insights")
    .select("payload, generated_at")
    .eq("connection_id", connectionId)
    .eq("kind", "weekly_digest")
    .order("generated_at", { ascending: false })
    .limit(1)
    .maybeSingle();

  const { data: isPremium } = await supabase.rpc("connection_has_premium", {
    p_conn: connectionId,
  });

  const rawPayload = insight?.payload ?? null;
  const pending = isPendingInsightPayload(rawPayload);
  const payload = (pending ? null : rawPayload) as Payload | null;
  const generatedAt = pending ? null : (insight?.generated_at ?? null);
  const canRegenerate =
    !pending &&
    (!generatedAt || Date.now() - new Date(generatedAt).getTime() >= DIGEST_MIN_GAP_MS);
  const generate = generateWeeklyDigest.bind(null, connectionId);

  // Only offer generation when the week actually has revealed answers —
  // otherwise the button's only possible outcome is an error.
  const since = new Date(Date.now() - 7 * 24 * 60 * 60 * 1000).toISOString();
  const { count: weekCount } = await supabase
    .from("prompt_instances")
    .select("id", { count: "exact", head: true })
    .eq("connection_id", connectionId)
    .eq("status", "revealed")
    .gte("revealed_at", since);
  const hasMaterial = (weekCount ?? 0) > 0;

  const autoStarted = shouldAutoGenerateDigest({
    isPremium: !!isPremium,
    aiEnabled: aiEnabled(),
    hasMaterial,
    pending,
    lastGeneratedAt: generatedAt,
  });
  if (autoStarted) {
    // The session client was created during render; after() must not read
    // request APIs itself in a server component. Failures leave the button.
    after(() => runWeeklyDigest(supabase, user.id, connectionId, "auto").catch(() => undefined));
  }

  return (
    <section className="card mt-6">
      <h2 className="text-lg">Weekly digest</h2>

      {payload?.safety ? (
        <div className="mt-3 rounded-lg border border-rose-200 dark:border-rose-900/50 bg-rose-50 dark:bg-rose-950/40 p-4">
          <p className="text-sm text-rose-900 dark:text-rose-200">{SAFETY_NOTE}</p>
          <p className="mt-2 text-sm text-rose-900/90 dark:text-rose-200/90">
            {SAFETY_PRIVACY_LINE}
          </p>
          <ul className="mt-2 space-y-1 text-sm">
            {INLINE_RESOURCES.map((r) => (
              <li key={r.name}>
                <span className="font-medium">{r.name}:</span> {r.contact}
              </li>
            ))}
          </ul>
          <Link href="/safety" className="mt-2 inline-block text-sm underline">
            More resources →
          </Link>
        </div>
      ) : payload ? (
        <div className="mt-2 space-y-3 text-sm text-ink-soft">
          {generatedAt && (
            <p className="text-xs text-ink-soft/80">
              From your week up to {generatedAt.slice(0, 10)}
            </p>
          )}
          {!!payload.highlights?.length && (
            <div>
              <h3 className="font-medium">Bright spots</h3>
              <ul className="mt-1 list-disc pl-5 space-y-1">
                {payload.highlights.map((h, i) => (
                  <li key={i}>{h}</li>
                ))}
              </ul>
            </div>
          )}
          {!!payload.appreciations?.length && (
            <div>
              <h3 className="font-medium">Worth a thank-you</h3>
              <ul className="mt-1 list-disc pl-5 space-y-1">
                {payload.appreciations.map((a, i) => (
                  <li key={i}>{a}</li>
                ))}
              </ul>
            </div>
          )}
          {payload.gentle_suggestion && (
            <div>
              <h3 className="font-medium">One small thing to try</h3>
              <p className="mt-1">{payload.gentle_suggestion}</p>
            </div>
          )}
          {payload.reflection && (
            <p className="text-ink-soft whitespace-pre-wrap">{payload.reflection}</p>
          )}
        </div>
      ) : (
        <p className="mt-1 text-sm text-ink-soft">
          A short AI reflection on the week you answered together — bright
          spots, appreciations, and one small thing to try.
        </p>
      )}

      {isPremium && (pending || autoStarted) ? (
        <p className="mt-3 text-sm text-ink-soft">
          This week&apos;s digest is being written. It will be here the next
          time you open this page.
        </p>
      ) : isPremium ? (
        canRegenerate &&
        (hasMaterial ? (
          <form action={generate} className="mt-3">
            <PendingButton pendingLabel="Writing your digest…">
              {payload ? "Generate this week's digest" : "Generate weekly digest"}
            </PendingButton>
          </form>
        ) : (
          <p className="mt-3 text-sm text-ink-soft/80">
            Answer a daily question together this week and the digest unlocks.
          </p>
        ))
      ) : (
        <p className="mt-3 text-sm text-ink-soft">
          Part of{" "}
          <Link href="/pricing" className="text-brand-700 underline dark:text-brand-300">
            Premium
          </Link>
          {" "}— your questions, reveals, and safety resources stay free.
        </p>
      )}

      {isPremium && (
        <p className="mt-2 text-xs text-ink-soft/80">
          Written automatically once a week when either of you opens this
          page. Your week&apos;s revealed answers are sent to our AI provider
          (xAI&apos;s Grok) with names and contact details removed, used only
          to write this digest.
        </p>
      )}
    </section>
  );
}
